"""Compare the panel of variant `main` with other variants -> reports/variants.md.

micromamba run -n demand-showcase python scripts/compare_variants.py dedup [...]
"""

import json
import sys

import pandas as pd

from retail.io import REPO_DIR, data_dir
from retail.variants import sku_changes, summary, weekly_changes


def load(name: str):
    folder = data_dir() / "processed" / ("" if name == "main" else f"variants/{name}")
    meta = json.loads((folder / "panel_meta.json").read_text())
    return pd.read_parquet(folder / "panel_weekly.parquet"), meta


def main() -> None:
    base, base_meta = load("main")
    out = ["# Data variants", "", "Generated by scripts/compare_variants.py.", ""]
    out += ["| Variant | Data version | SKUs | Rows | Units | Revenue (£) | Zero weeks |"]
    out += ["|---|---|---:|---:|---:|---:|---:|"]
    variants = [(n, *load(n)) for n in sys.argv[1:]]
    for name, p, meta in [("main", base, base_meta), *variants]:
        s = summary(p)
        out.append(
            f"| {name} ({meta['config']['duplicates']} duplicates) | {meta['data_version']} | "
            f"{s['skus']} | {s['rows']} | {s['units']:,.0f} | {s['revenue']:,.0f} | "
            f"{s['zero_weeks']:.1%} |"
        )
    for name, p, _ in variants:
        ch = sku_changes(base, p)
        rel = ch["rel_change"].dropna()
        w = weekly_changes(base, p)["rel_change"].dropna()
        out += [
            "",
            f"## main vs. {name}",
            "",
            f"- SKUs with any change in total units: {(rel != 0).sum()} of {len(ch)}; "
            f"|change| > 1 %: {(rel.abs() > 0.01).sum()}, > 5 %: {(rel.abs() > 0.05).sum()}, "
            f"> 20 %: {(rel.abs() > 0.2).sum()}; "
            f"only in one variant: {ch['rel_change'].isna().sum()}.",
            f"- Weekly total units: change between {w.min():.2%} and {w.max():.2%} "
            f"(median {w.median():.2%}).",
            "",
            "Largest relative changes per SKU (total units):",
            "",
            "| SKU | main | " + name + " | change |",
            "|---|---:|---:|---:|",
        ]
        for code, r in ch.head(10).iterrows():
            out.append(
                f"| {code} | {r['units_base']:,.0f} | {r['units_other']:,.0f} | "
                f"{r['rel_change']:.1%} |"
            )
    text = "\n".join(out) + "\n"
    (REPO_DIR / "reports" / "variants.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
