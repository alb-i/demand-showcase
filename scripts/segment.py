"""Segments and the focus set.

    micromamba run -n demand-showcase python scripts/segment.py

Reads the main panel ($DATA_DIR/processed) and configs/backtest.yaml; writes
reports/segments.{csv,md}, $DATA_DIR/processed/segments.parquet and the focus set at the end of
configs/backtest.yaml (below the marker line, regenerated on every run).
"""

import json

import pandas as pd
import yaml

from retail.io import REPO_DIR, data_dir
from retail.segments import (
    SB_CLASSES,
    class_table,
    history,
    segment_table,
    without_large_orders,
)

CONFIG = REPO_DIR / "configs" / "backtest.yaml"
MARKER = "# --- focus set: generated by scripts/segment.py"


def write_focus(path, codes: list[str], meta: dict) -> None:
    text = path.read_text()
    head = text[: text.index(MARKER)]
    marker_line = text[text.index(MARKER) :].splitlines()[0]
    block = yaml.safe_dump({"focus_set": {**meta, "stock_codes": codes}}, sort_keys=False)
    path.write_text(head + marker_line + "\n" + block)


def md_table(df: pd.DataFrame) -> list[str]:
    cols = [df.index.name or "", *df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, r in df.iterrows():
        cells = [f"{v:.1%}" if "share" in c else f"{v:.0f}" for c, v in r.items()]
        out.append(f"| {idx} | " + " | ".join(cells) + " |")
    return out


def main() -> None:
    cfg = yaml.safe_load(CONFIG.read_text())["segments"]
    processed = data_dir() / "processed"
    panel = pd.read_parquet(processed / "panel_weekly.parquet")
    sales = pd.read_parquet(processed / "sales_clean.parquet")
    meta = json.loads((processed / "panel_meta.json").read_text())

    seg = segment_table(panel, sales, cfg)
    single = segment_table(panel, sales, cfg | {"min_demand_weeks": 1})
    single = single[~single["stock_code"].isin(seg["stock_code"])]
    desc = panel.drop_duplicates("stock_code").set_index("stock_code")["description"]
    seg.insert(1, "description", seg["stock_code"].map(desc))
    seg.to_parquet(processed / "segments.parquet", index=False)
    rounded = seg.round(
        {"revenue": 2, "revenue_share": 6, "cv": 3, "cv_nonzero": 3, "adi": 3, "cv2": 3}
    )
    rounded.round({"top_customer_share": 3}).to_csv(
        REPO_DIR / "reports" / "segments.csv", index=False
    )

    focus = seg[seg["focus"]]
    codes = sorted(focus["stock_code"])
    write_focus(
        CONFIG,
        codes,
        {"data_version": meta["data_version"], "before": cfg["before"], "n": len(codes)},
    )

    sb = class_table(seg, "sb_class").reindex(SB_CLASSES)
    sb_lines = []
    ratio = cfg["syntetos_boylan"].get("max_order_ratio")
    if ratio:
        hist = history(panel, cfg["before"])
        kept = sales[sales["stock_code"].isin(seg["stock_code"])]
        _, large = without_large_orders(hist, kept, cfg["before"], ratio)
        total = kept.loc[kept["invoice_date"] < pd.Timestamp(cfg["before"]), "quantity"].sum()
        moves = pd.crosstab(seg["sb_class_all"], seg["sb_class"]).reindex(
            index=SB_CLASSES, columns=SB_CLASSES, fill_value=0
        )
        moves.index.name = "all lines \\ without large"
        sb_all = class_table(seg, "sb_class_all").reindex(SB_CLASSES)
        sb_all.index.name = "Syntetos-Boylan (all lines)"
        sb_lines = [
            f"ADI and CV^2 ignore {len(large):,} lines with more than {ratio}x the product's "
            f"median line quantity ({large['quantity'].sum() / total:.1%} of the units, "
            f"{large['stock_code'].nunique()} products). The class on all lines is "
            "`sb_class_all` in segments.csv.",
            "",
            "Products per class, all lines (rows) vs. without large orders (columns):",
            "",
            "| " + " | ".join([moves.index.name, *moves.columns]) + " |",
            "|" + "---|" * (len(moves.columns) + 1),
            *[f"| {i} | " + " | ".join(str(v) for v in r) + " |" for i, r in moves.iterrows()],
            "",
            "On all lines:",
            "",
            *md_table(sb_all),
            "",
        ]
    sb.index.name = "Syntetos-Boylan"
    abc = class_table(seg, "abc")
    abc.index.name = "ABC"
    grid = pd.crosstab(seg["abc"], seg["xyz"], values=seg["revenue"], aggfunc="sum")
    grid = (grid / seg["revenue"].sum()).fillna(0)
    counts = pd.crosstab(seg["abc"], seg["xyz"])
    conc = seg["top_customer_share"]
    lines = [
        "# Segments",
        "",
        f"Data version `{meta['data_version']}`; weeks before {cfg['before']} (first test origin). "
        f"{len(seg)} products with demand in at least {cfg.get('min_demand_weeks', 1)} "
        f"weeks of that period, {seg['revenue'].sum():,.0f} GBP; left out: {len(single)} "
        f"products with demand in a single week, {single['revenue'].sum():,.0f} GBP "
        f"({single['revenue'].sum() / (seg['revenue'].sum() + single['revenue'].sum()):.2%}).",
        "",
        f"**Focus set**: {len(codes)} products ({'/'.join(cfg['focus']['classes'])} with >= "
        f"{cfg['focus']['min_active_weeks']} active weeks), "
        f"{focus['revenue'].sum() / seg['revenue'].sum():.1%} of revenue. "
        "Listed in configs/backtest.yaml (`focus_set`).",
        "",
        "## ABC (revenue)",
        "",
        *md_table(abc),
        "",
        "## ABC x XYZ (revenue share; products in brackets)",
        "",
        "| ABC | " + " | ".join(grid.columns) + " |",
        "|---|" + "---|" * len(grid.columns),
        *[
            f"| {a} | "
            + " | ".join(f"{grid.loc[a, x]:.1%} ({counts.loc[a, x]})" for x in grid.columns)
            + " |"
            for a in grid.index
        ],
        "",
        "## Syntetos-Boylan classes (ADI 1.32, CV^2 0.49)",
        "",
        *sb_lines,
        "Without large orders:" if ratio else "",
        "",
        *md_table(sb),
        "",
        "## Customer concentration",
        "",
        f"- One customer buys > 50 % of the units of {(conc > 0.5).sum()} products "
        f"({(conc > 0.5).mean():.1%}; focus set: {(focus['top_customer_share'] > 0.5).sum()}), "
        f"> 80 % of {(conc > 0.8).sum()}.",
        "- Median top-customer share by Syntetos-Boylan class: "
        + ", ".join(
            f"{c} {seg.loc[seg['sb_class'] == c, 'top_customer_share'].median():.0%}"
            for c in SB_CLASSES
        )
        + ".",
        "",
    ]
    (REPO_DIR / "reports" / "segments.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
